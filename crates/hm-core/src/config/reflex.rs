pub const REFLEX_KEY: &str = "reflex";

/// R1j/P1: the device-side reflex vocabulary — ONE source for what the
/// keyword spotter listens for (word, device token spelling, intent).
/// `kw.txt` is COMPILED from this block and never hand-edited onto the
/// device. The text layer keeps its own broader synonym lists as the ASR
/// fallback; those are a different mechanism and are deliberately not
/// merged (KWS = reflex, ASR = semantics).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ReflexIntent {
    /// The wake phrase: stop what plays, open the follow window.
    Wake,
    /// Session end (「退下」＝除断电清零, user decision 2026-11-12).
    Retreat,
    /// Pause the live program; the bookmark is kept.
    Pause,
    /// Resume the bookmarked program.
    Continue,
    /// M3: next track in the media queue.
    Next,
    /// M3: stop and discard (media session or program).
    Stop,
}

impl ReflexIntent {
    pub fn word(self) -> &'static str {
        match self {
            ReflexIntent::Wake => "wake",
            ReflexIntent::Retreat => "retreat",
            ReflexIntent::Pause => "pause",
            ReflexIntent::Continue => "continue",
            ReflexIntent::Next => "next",
            ReflexIntent::Stop => "stop",
        }
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ReflexWord {
    /// What the person says (console label and the spotter's keyword line).
    pub text: String,
    /// Device token spelling, space separated — the MODEL's tokens from
    /// `tokens.txt`, not syllables: `z àn t íng b ō f àng`. A token outside
    /// the table invalidates the WHOLE keyword file on the device
    /// (measured 2026-11-12: sherpa logs "Encode keywords failed" and spots
    /// nothing while the driver still reports ready).
    pub tokens: String,
    pub intent: ReflexIntent,
    #[serde(default = "default_true")]
    pub enabled: bool,
}

#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct ReflexConfig {
    #[serde(default = "default_reflex_words")]
    pub words: Vec<ReflexWord>,
}

impl Default for ReflexConfig {
    fn default() -> Self {
        Self {
            words: default_reflex_words(),
        }
    }
}

