/// Contract v2 §2.5 (#5, 2026-11-16): the two facts the device needs to act
/// on a word without the core — WHICH words mean "exit" and a version of the
/// word→intent map they came from. Only enabled words count: a disabled word
/// is not in the compiled file, so arming it would arm a word the spotter
/// cannot hear.
///
/// The hash covers text and intent (not tokens), so the same vocabulary with
/// a different meaning — the 2026-11-15「停止播放」stop→retreat move — is a
/// different version. The deploy receipt echoes it next to the file hash: the
/// vocabulary and its meaning are two different facts.
pub fn reflex_intent_map(cfg: &ReflexConfig) -> (Vec<String>, String) {
    let enabled: Vec<&ReflexWord> = cfg.words.iter().filter(|w| w.enabled).collect();
    let mut lines = String::new();
    for w in &enabled {
        lines.push_str(&format!("{}\t{}\n", w.text.trim(), w.intent.word()));
    }
    let retreat = enabled
        .iter()
        .filter(|w| w.intent == ReflexIntent::Retreat)
        .map(|w| w.text.trim().to_string())
        .collect();
    (retreat, fnv1a_hex(lines.as_bytes()))
}

/// Compile enabled words into the device keywords file. Every refusal is
/// named and actionable: a half-valid file is worse than a rejection, since
/// the device spots NOTHING when one line fails to encode — silently.
pub fn compile_keywords(cfg: &ReflexConfig) -> std::result::Result<String, String> {
    let enabled: Vec<&ReflexWord> = cfg.words.iter().filter(|w| w.enabled).collect();
    if enabled.is_empty() {
        return Err("没有启用的词：至少保留唤醒词".into());
    }
    let mut out = String::new();
    let mut seen: Vec<String> = Vec::new();
    for w in &enabled {
        let text = w.text.trim();
        if text.is_empty() || text.chars().count() > 12 {
            return Err(format!("词「{text}」长度不合法（1–12 字）"));
        }
        if text.contains('@') || text.chars().any(char::is_whitespace) {
            return Err(format!("词「{text}」不能含 @ 或空白"));
        }
        if seen.iter().any(|s| s == text) {
            return Err(format!("词「{text}」重复"));
        }
        seen.push(text.to_string());
        let tokens: Vec<&str> = w.tokens.split_whitespace().collect();
        // Short words are allowed: the spotter will most likely miss them
        // (measured: 4-token phrases 0/5 at every threshold), but the SAME
        // table is executed from the transcript, so the word still works at
        // ASR latency. [`reflex_warnings`] states the trade-off.
        if tokens.len() > 16 {
            return Err(format!("词「{text}」token 太多（上限 16）"));
        }
        if tokens.iter().any(|t| t.contains('@') || t.contains('\n')) {
            return Err(format!("词「{text}」的 token 拼写不合法"));
        }
        out.push_str(&format!("{} @{}\n", tokens.join(" "), text));
    }
    Ok(out)
}

/// R1j/P1: 汉字 → the device's token spelling, generated instead of typed.
///
/// The model's table is initial + tone-marked final (`暂停播放` →
/// `z àn t íng b ō f àng`), which is not something a person should have to
/// spell by hand — one wrong final silently kills the whole keyword file.
/// Rules kept here, measured against the table the device actually loads:
/// - `pinyin 0.11` supplies the tone-marked syllable (already a dependency:
///   the wake matcher uses its plain form);
/// - split after the initial (`zh/ch/sh` first), the final keeps its mark;
/// - 一/不 tone sandhi is applied (一 before 4th → yí, otherwise yì; 不 before
///   4th → bú), because the TTS/pronunciation uses the sandhi form;
/// - third-tone sandhi is NOT applied (你好 stays `n ǐ h ǎo`, matching the
///   shipped wake line);
/// - neutral tone loses the mark (`吧` → `b a`), which is how the table
///   spells it.
pub fn reflex_tokens(text: &str) -> std::result::Result<String, String> {
    use pinyin::ToPinyin;
    let chars: Vec<char> = text.chars().filter(|c| !c.is_whitespace()).collect();
    if chars.is_empty() {
        return Err("词是空的".into());
    }
    // (syllable with tone, tone number)
    let mut syl: Vec<(String, u32)> = Vec::new();
    for c in &chars {
        let Some(py) = c.to_pinyin() else {
            return Err(format!("「{c}」不是汉字，无法自动生成拼写"));
        };
        // with_tone_num() embeds the digit ("zan4" style: "za4n" → take the
        // ASCII digit); 0 = neutral.
        let tone = py
            .with_tone_num()
            .chars()
            .find_map(|c| c.to_digit(10))
            .unwrap_or(0);
        syl.push((py.with_tone().to_string(), tone));
    }
    let mut tokens: Vec<String> = Vec::new();
    for (i, (s, tone)) in syl.iter().enumerate() {
        let base = s.as_str();
        // 一 / 不 sandhi (the only two that change the spoken tone in place).
        let (base, _tone) = if base.starts_with('y') && base.trim_start_matches('y') == "ī" {
            let next = syl.get(i + 1).map(|(_, t)| *t).unwrap_or(0);
            let replaced = if next == 4 {
                "yí"
            } else if next > 0 {
                "yì"
            } else {
                "yī"
            };
            (replaced, if next == 4 { 2 } else { 4 })
        } else if base == "bù" {
            let next = syl.get(i + 1).map(|(_, t)| *t).unwrap_or(0);
            (if next == 4 { "bú" } else { "bù" }, *tone)
        } else {
            (base, *tone)
        };
        let (initial, final_) = split_initial(base);
        if initial.is_empty() {
            tokens.push(final_.to_string());
        } else {
            tokens.push(initial.to_string());
            tokens.push(final_.to_string());
        }
    }
    Ok(tokens.join(" "))
}

/// Split a tone-marked pinyin syllable after its initial. `zh/ch/sh` are two
/// letters; `y/w` are initials too (the table has `ǐ`, `ǒu`, `uè` as finals).
fn split_initial(syl: &str) -> (&str, &str) {
    for ini in ["zh", "ch", "sh"] {
        if let Some(rest) = syl.strip_prefix(ini) {
            if !rest.is_empty() {
                return (ini, rest);
            }
        }
    }
    let mut it = syl.char_indices();
    let Some((_, first)) = it.next() else {
        return ("", "");
    };
    if matches!(
        first,
        'b' | 'p'
            | 'm'
            | 'f'
            | 'd'
            | 't'
            | 'n'
            | 'l'
            | 'g'
            | 'k'
            | 'h'
            | 'j'
            | 'q'
            | 'x'
            | 'r'
            | 'z'
            | 'c'
            | 's'
            | 'y'
            | 'w'
    ) {
        let end = syl.len() - syl.trim_start_matches(first).len();
        (&syl[..end], &syl[end..])
    } else {
        ("", syl)
    }
}

/// R1j/P1: deploy-time warnings (never refusals). Stated where the console
/// and the API answer, so "this word will probably rely on the text layer"
/// is visible BEFORE deploying — not discovered as silence.
pub fn reflex_warnings(cfg: &ReflexConfig) -> Vec<String> {
    let mut out = Vec::new();
    // Audit R2-24: the table can be emptied (or all its wake words disabled)
    // and still deploy, after which the device-side spotter has no wake
    // phrase at all. That is a legitimate configuration — the text layer can
    // still wake it — but only while `asr_wake_fallback` is on, so say it
    // BEFORE deploying rather than let it look like a broken microphone.
    let wake_enabled = cfg
        .words
        .iter()
        .filter(|w| w.enabled && w.intent == ReflexIntent::Wake)
        .count();
    if wake_enabled == 0 {
        let enabled = cfg.words.iter().filter(|w| w.enabled).count();
        out.push(format!(
            "没有启用的「唤醒」意图词（{} 个启用词都不唤醒）：设备端关键词将无法唤醒。若「语音转写（唤醒兜底）」也关着，这个房间就只能靠按键或控制台唤醒。",
            enabled
        ));
    }
    for w in cfg.words.iter().filter(|w| w.enabled) {
        let n = w.tokens.split_whitespace().count();
        // Short words are a caution, not a wall: the 2026-11-13 S1 re-test
        // shows the TONED spelling of 退下/继续 (4 tokens) fires, while
        // 暂停/拜拜 (4 tokens) does not. Whether a word hits is per-word and
        // per-spelling; the per-word hits counter after deploying is the
        // honest answer, and the text layer is the ~1 s fallback.
        if n < 8 {
            out.push(format!(
                "词「{}」有 {} 个 token：短词是否进反射取决于词与拼写（实测带调 退下/继续 可命中，暂停/拜拜 不命中）；部署后看该词 hits，没命中会走转写（约 1 s）",
                w.text.trim(),
                n
            ));
        }
    }
    out
}
